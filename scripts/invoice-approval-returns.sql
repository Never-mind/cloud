CREATE TABLE IF NOT EXISTS merge_common_invoice_approval_files (
  internalId BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  id CHAR(36) NOT NULL,
  instanceCode VARCHAR(64) NOT NULL,
  contentHash CHAR(64) NOT NULL,
  remoteKey CHAR(64) NOT NULL,
  fileName VARCHAR(500) NOT NULL,
  fileType VARCHAR(100) NOT NULL,
  fileSize INT UNSIGNED NOT NULL,
  storageProvider VARCHAR(16) NOT NULL,
  storageKey VARCHAR(1024) NULL,
  dataUrl LONGTEXT NULL,
  uploadedAt VARCHAR(40) NULL,
  nodeId VARCHAR(128) NULL,
  origin VARCHAR(16) NOT NULL,
  recognitionJson LONGTEXT NULL,
  recognitionError VARCHAR(1000) NULL,
  invoiceIdentity CHAR(64) NULL,
  invoiceNo VARCHAR(128) NULL,
  invoiceId CHAR(36) NULL,
  confirmedJson LONGTEXT NULL,
  confirmedBy VARCHAR(128) NULL,
  confirmedAt DATETIME NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_invoice_approval_file_id (id),
  UNIQUE KEY uk_invoice_approval_file_hash (instanceCode, contentHash),
  KEY idx_invoice_approval_file_identity (instanceCode, invoiceIdentity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
