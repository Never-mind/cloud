function splitFieldName(fieldName) {
  return fieldName
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .split(/[_\s-]+/)
    .filter(Boolean)
    .map((word) => word.toLowerCase());
}

function genericFieldComment(fieldName) {
  const labels = splitFieldName(fieldName).map((word) => WORD_LABELS[word] ?? "扩展");
  return labels.length > 0 ? labels.join("") : "业务字段";
}

function escapeIdentifier(identifier) {
  return `\`${identifier.replaceAll("`", "``")}\``;
}

function removeColumnComment(definition) {
  return definition.replace(/\s+COMMENT\s+'(?:[^'\\]|\\.)*'/i, "").replace(/,\s*$/, "");
}

async function getTargetTables(connection, database) {
  const [rows] = await connection.execute(
    `SELECT TABLE_NAME, TABLE_COMMENT
       FROM information_schema.TABLES
      WHERE TABLE_SCHEMA = ?
      ORDER BY TABLE_NAME`,
    [database],
  );
  return rows.filter((row) =>
    ["merge_common_", "merge_po_", "merge_cloud_", "merge_power_"].some((prefix) => row.TABLE_NAME.startsWith(prefix)),
  );
}

async function updateTableComment(connection, tableName, currentComment, dryRun) {
  const targetComment = TABLE_COMMENTS[tableName] ?? "未分类业务数据表";
  if (currentComment === targetComment) return false;
  if (!dryRun) {
    await connection.query(
      `ALTER TABLE ${escapeIdentifier(tableName)} COMMENT = ?`,
      [targetComment],
    );
  }
  return true;
}

async function updateColumnComment(connection, tableName, column, createSql, dryRun) {
  const fieldName = column.Field;
  const targetComment = FIELD_COMMENTS[fieldName] ?? genericFieldComment(fieldName);
  if (column.Comment === targetComment) return false;

  const lines = createSql.split(/\r?\n/);
  const fieldPrefix = `${escapeIdentifier(fieldName)} `;
  const lineIndex = lines.findIndex((line) => line.trimStart().startsWith(fieldPrefix));
  if (lineIndex < 0) {
    throw new Error(`无法从 SHOW CREATE TABLE 找到字段定义：${tableName}.${fieldName}`);
  }

  const originalLine = lines[lineIndex];
  const baseDefinition = removeColumnComment(originalLine.trim());
  const newDefinition = `${baseDefinition} COMMENT ${connection.escape(targetComment)}`;
  if (!dryRun) {
    await connection.query(
      `ALTER TABLE ${escapeIdentifier(tableName)} MODIFY COLUMN ${newDefinition}`,
    );
  }
  return true;
}

export async function applyChineseComments(connection, database, options = {}) {
  const dryRun = options.dryRun ?? process.env.DRY_RUN === "1";
  const tables = await getTargetTables(connection, database);
  let updatedTables = 0;
  let updatedColumns = 0;

  for (const table of tables) {
    if (await updateTableComment(connection, table.TABLE_NAME, table.TABLE_COMMENT, dryRun)) {
      updatedTables += 1;
    }

    const [columnRows] = await connection.query(
      `SHOW FULL COLUMNS FROM ${escapeIdentifier(table.TABLE_NAME)}`,
    );
    const [createRows] = await connection.query(
      `SHOW CREATE TABLE ${escapeIdentifier(table.TABLE_NAME)}`,
    );
    const createSql = createRows[0]?.["Create Table"];
    if (!createSql) throw new Error(`无法读取表定义：${table.TABLE_NAME}`);

    for (const column of columnRows) {
      if (await updateColumnComment(connection, table.TABLE_NAME, column, createSql, dryRun)) {
        updatedColumns += 1;
      }
    }
  }

  return { tableCount: tables.length, updatedTables, updatedColumns, dryRun };
}

