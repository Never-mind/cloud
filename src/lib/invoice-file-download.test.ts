import { beforeEach, describe, expect, it, vi } from "vitest";
const mocks=vi.hoisted(()=>({ query:vi.fn(),execute:vi.fn(),read:vi.fn(),store:vi.fn(),pdf:vi.fn() }));
vi.mock("./db",()=>({queryRowsRaw:mocks.query,executeRaw:mocks.execute,queryRowsInTransaction:mocks.query,executeInTransaction:mocks.execute,withTransaction:vi.fn()}));
vi.mock("./file-storage-service",()=>({readFile:mocks.read,storeFile:mocks.store,deleteFileObject:vi.fn()}));
vi.mock("./invoice-pdf",()=>({renderInvoicePdf:mocks.pdf}));
import { readInvoiceFile, saveInvoice, regenerateInvoiceFile } from "./invoice-service";
import { readInvoiceAttachmentFile } from "./invoice-attachment-download";
const html='<html><head></head><body>Archived customer and 123.45 USD</body></html>';
const pdf=Buffer.from('%PDF-1.7\nfixture');
const row={source:'generated',invoiceNo:'WZ-202611-0002',fileName:'old.html',fileType:'text/html',fileProvider:'obs',storageKey:'invoice/old.html'};
beforeEach(()=>{vi.resetAllMocks();mocks.query.mockResolvedValue([row]);mocks.read.mockResolvedValue({bytes:Buffer.from(html),contentType:'text/html'});mocks.pdf.mockResolvedValue(pdf);});
describe('invoice file download compatibility',()=>{
 it('converts archived HTML without rebuilding partner data or modifying any records',async()=>{
  expect(await readInvoiceFile('invoice')).toEqual({bytes:pdf,contentType:'application/pdf',fileName:'old.pdf'});
  expect(mocks.pdf).toHaveBeenCalledWith(html);expect(mocks.query).toHaveBeenCalledTimes(1);expect(mocks.execute).not.toHaveBeenCalled();expect(mocks.store).not.toHaveBeenCalled();
 });
 it('keeps actual PDF bytes and fixes stale HTML metadata',async()=>{
  mocks.read.mockResolvedValue({bytes:pdf,contentType:'text/html'});
  expect(await readInvoiceFile('invoice')).toEqual({bytes:pdf,contentType:'application/pdf',fileName:'old.pdf'});expect(mocks.pdf).not.toHaveBeenCalled();
 });
 it('detects HTML even if a local invoice was mislabeled PDF',async()=>{
  mocks.query.mockResolvedValue([{...row,fileName:'old.pdf',fileType:'application/pdf'}]);
  expect((await readInvoiceFile('invoice'))?.bytes).toEqual(pdf);expect(mocks.pdf).toHaveBeenCalledWith(html);
 });
 it.each(['text/html','text/xml','text/plain'])('preserves external %s originals',async contentType=>{
  mocks.query.mockResolvedValue([{...row,source:'external',fileType:contentType}]);
  mocks.read.mockResolvedValue({bytes:Buffer.from(html),contentType});
  expect((await readInvoiceFile('invoice'))?.contentType).toBe(contentType);expect(mocks.pdf).not.toHaveBeenCalled();
 });
 it('rejects corrupt generated bytes instead of renaming them PDF',async()=>{
  mocks.read.mockResolvedValue({bytes:Buffer.from('broken'),contentType:'application/pdf'});
  await expect(readInvoiceFile('invoice')).rejects.toThrow('文件损坏');expect(mocks.pdf).not.toHaveBeenCalled();
 });
 it('reports conversion errors instead of serving archived HTML',async()=>{
  mocks.pdf.mockRejectedValue(Object.assign(new Error('PDF unavailable'),{status:503}));
  await expect(readInvoiceFile('invoice')).rejects.toMatchObject({status:503});expect(mocks.store).not.toHaveBeenCalled();
 });
 it('preserves parameterized historical data URLs for decoding',async()=>{
  mocks.query.mockResolvedValue([{...row,fileProvider:'db',fileContent:`data:text/html; charset=utf-8;base64,${Buffer.from(html).toString('base64')}`}]);
  await readInvoiceFile('invoice');expect(mocks.read).toHaveBeenCalledWith(expect.objectContaining({dataUrl:`data:application/octet-stream;base64,${Buffer.from(html).toString('base64')}`}));
 });
 it.each(['obs','db'])('converts linked source attachments stored in %s',async storageProvider=>{
  mocks.query.mockResolvedValue([{invoiceNo:row.invoiceNo}]);
  expect(await readInvoiceAttachmentFile({fileName:'old.html',storageProvider,storageKey:'invoice/old.html',dataUrl:'stored-html'})).toEqual({bytes:pdf,contentType:'application/pdf',fileName:'old.pdf'});
  expect(mocks.query.mock.calls[0][0]).toContain("source='generated'");
  expect(mocks.query.mock.calls[0][1]).toEqual(storageProvider==='obs'?{storageKey:'invoice/old.html'}:{dataUrl:'stored-html'});
 });
 it('leaves unlinked HTML uploads untouched',async()=>{
  mocks.query.mockResolvedValue([]);const result=await readInvoiceAttachmentFile({fileName:'uploaded.html',storageProvider:'obs',storageKey:'external.html'});
  expect(result?.contentType).toBe('text/html');expect(mocks.pdf).not.toHaveBeenCalled();
 });
});

describe('failed local issuance',()=>{
 const input={source:'generated' as const,sourceType:'manual' as const,invoiceNo:'WZ-TEST',invoiceDate:'2026-11-12',dueDate:'2026-12-12',paymentTermDays:30,currency:'USD',amountIncludingTax:'100',amountExcludingTax:'100',taxRate:'0',customerId:'customer',undertakingUnitId:'unit',customerName:'Buyer',customerAddress:'Buyer address',sellerName:'Seller',sellerCountry:'HK',sellerAddress:'Seller address',bankAccount:'12345',lines:[{periodLabel:'202611',description:'Service fee',amount:'100'}]};
 it.each(['save','regenerate'])('%s never persists an HTML fallback or changes amounts on PDF failure',async action=>{
  mocks.query.mockImplementation(async(sql:string)=>sql.includes('FROM merge_common_customers')?[{customerId:'customer',name:'Buyer'}]:sql.includes('FROM merge_common_undertaking_units')?[{undertakingUnitId:'unit',name:'Seller'}]:sql.includes('FROM merge_common_invoices i')?[{...input,id:'invoice'}]:sql.includes('FROM merge_common_invoice_items')?[{periodLabel:'202611',description:'Service fee',amount:'100'}]:[]);
  mocks.pdf.mockRejectedValue(new Error('PDF failure'));
  await expect(action==='save'?saveInvoice(input):regenerateInvoiceFile('invoice')).rejects.toThrow('PDF failure');
  expect(mocks.store).not.toHaveBeenCalled();expect(mocks.execute).not.toHaveBeenCalled();
 });
});
